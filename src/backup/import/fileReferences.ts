// Tool data is an open external JSON shape. Only known Ema file references are changed.
function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

export function rewriteFileReferences(
  blocksJson: string,
  attachments: ReadonlyMap<string, string>,
  resources: ReadonlyMap<string, string>,
): string {
  let blocks: unknown;
  try {
    blocks = JSON.parse(blocksJson);
  } catch {
    return blocksJson;
  }
  if (!Array.isArray(blocks)) return blocksJson;
  for (const block of blocks) {
    if (!isObject(block)) continue;
    if ((block.type === 'image_reference' || block.type === 'pasted_text_reference')
      && typeof block.path === 'string') {
      block.path = attachments.get(block.path) ?? block.path;
    } else if (block.type === 'tool_use' && block.name === 'Read'
      && isObject(block.args) && typeof block.args.file_path === 'string') {
      const oldPath = block.args.file_path;
      block.args.file_path = resources.get(oldPath) ?? attachments.get(oldPath) ?? oldPath;
    } else if (block.type === 'tool_result') {
      if (typeof block.content === 'string') {
        block.content = rewriteToolText(block.content, resources);
      } else if (Array.isArray(block.content)) {
        for (const part of block.content) {
          if (isObject(part) && part.type === 'text' && typeof part.text === 'string') {
            part.text = rewriteToolText(part.text, resources);
          }
        }
      }
      if (isObject(block.data) && isObject(block.data.download)
        && typeof block.data.download.filePath === 'string') {
        const previous = block.data.download.filePath;
        const restored = resources.get(previous);
        if (restored) {
          block.data.download.filePath = restored;
          if (typeof block.data.content === 'string') {
            const content = rewriteToolText(block.data.content, resources);
            block.data.content = content;
            if (typeof block.data.totalLength === 'number') {
              block.data.totalLength = content.length;
            }
          }
        }
      }
    }
  }
  return JSON.stringify(blocks);
}

function rewriteToolText(content: string, paths: ReadonlyMap<string, string>): string {
  // This header is generated by ToolResultStore, not arbitrary quoted tool output.
  const persisted = /^(<persisted-output>\r?\nOutput too large \([^\r\n]*\)\. Full output saved to: )([^\r\n]+)(\r?\n)/;
  const rewritten = content.replace(persisted, (header, prefix: string, oldPath: string, newline: string) => {
    const restored = paths.get(oldPath);
    return restored ? `${prefix}${restored}${newline}` : header;
  });
  if (rewritten !== content) return rewritten;

  const download = /^(Downloaded \d+ bytes \([^\r\n]*\) to )([^\r\n]+)\.\r?\n/.exec(content);
  if (!download) return content;
  const oldPath = download[2]!;
  const restored = paths.get(oldPath);
  if (!restored) return content;
  const remaining = content.slice(download[0].length).replace(
    `Use Read with file_path=${JSON.stringify(oldPath)}`,
    `Use Read with file_path=${JSON.stringify(restored)}`,
  );
  return `${download[1]}${restored}.\n${remaining}`;
}
